//! Runtime `kitty.conf` generation (the analog of Zellij's merged config).
//!
//! kitty.conf supports `include`, so the runtime copy is the user's config
//! plus sat-hx-ide's `map` lines — no config parsing beyond a collision scan
//! of the user's `map` lines, mirroring the Zellij backend's policy of
//! refusing to shadow existing bindings.

use crate::config::KeybindingConfig;
use anyhow::{bail, Context, Result};
use std::fs;
use std::path::{Path, PathBuf};

pub struct KittyRuntimeConfigInput<'a> {
    /// User's kitty.conf, read-only merge source.
    pub source: Option<&'a Path>,
    pub destination: &'a Path,
    pub session_name: &'a str,
    pub keys: &'a KeybindingConfig,
    pub executable: &'a Path,
    pub app_config: &'a Path,
}

pub fn build_runtime_config(input: &KittyRuntimeConfigInput<'_>) -> Result<PathBuf> {
    let source_text = match input.source {
        Some(path) => fs::read_to_string(path)
            .with_context(|| format!("Failed to read kitty config {}", path.display()))?,
        None => String::new(),
    };
    let merged = merge_config(&source_text, input)?;

    if let Some(parent) = input.destination.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(input.destination, merged).with_context(|| {
        format!(
            "Failed to write private kitty config {}",
            input.destination.display()
        )
    })?;
    Ok(input.destination.to_path_buf())
}

/// Translate a sat-hx-ide key ("Ctrl y", "Alt Shift t") to kitty notation
/// ("ctrl+y", "alt+shift+t"). Also accepts already-kitty keys ("ctrl+y"), so
/// user `map` lines can be checked for collisions.
pub fn kitty_key(spec: &str) -> Result<String> {
    let mut parts = Vec::new();
    for token in spec.split_whitespace().flat_map(|token| token.split('+')) {
        if token.is_empty() {
            continue;
        }
        match token.to_ascii_lowercase().as_str() {
            "ctrl" | "control" => parts.push("ctrl".to_string()),
            "alt" | "option" => parts.push("alt".to_string()),
            "shift" => parts.push("shift".to_string()),
            other if other.chars().all(|c| c.is_ascii_alphanumeric()) => {
                parts.push(other.to_string())
            }
            _ => bail!("Unsupported kitty key component '{token}' in '{spec}'"),
        }
    }
    if parts.is_empty() {
        bail!("Empty keybinding '{spec}'");
    }
    Ok(parts.join("+"))
}

fn merge_config(source: &str, input: &KittyRuntimeConfigInput<'_>) -> Result<String> {
    let requested = [
        (&input.keys.file_manager, "file manager"),
        (&input.keys.file_manager_dock, "file-manager dock toggle"),
        (&input.keys.git, "Git client"),
        (&input.keys.review, "Review"),
        (&input.keys.workflow, "Workflow"),
        (&input.keys.terminal, "terminal toggle"),
        (&input.keys.terminal_zoom, "terminal zoom toggle"),
        (&input.keys.mindmap, "mind map toggle"),
        (&input.keys.mindmap_zoom, "mind map zoom toggle"),
        (&input.keys.venv, "venv toggle"),
        (&input.keys.venv_select, "venv selector"),
    ];
    let user_maps = user_map_keys(source);
    for (key, action) in requested {
        let kitty = kitty_key(key)?;
        if user_maps.contains(&kitty) {
            bail!(
                "kitty key '{kitty}' is already mapped; choose another \
                 [keybindings] value for the sat-hx-ide {action} action"
            );
        }
    }

    let mut out = String::new();
    out.push_str("# Generated by sat-hx-ide. Edits are overwritten.\n");
    if let Some(source) = input.source {
        out.push_str(&format!(
            "# User config, included read-only:\ninclude {}\n",
            source.display()
        ));
    }
    // Session identity for helper processes (kitty propagates conf `env` to
    // every window, so helpers can locate the session's runtime socket).
    out.push_str(&format!("\nenv SAT_SESSION_NAME={}\n", input.session_name));

    // Quit parity: Zellij has a built-in Ctrl+Q quit; kitty does not, so
    // the runtime config provides the same key. Unlike the helper maps,
    // a user binding on the same key wins — quitting is a convenience,
    // and their own binding may be intentional.
    let quit_key = kitty_key("Ctrl q")?;
    if user_maps.contains(&quit_key) {
        out.push_str(&format!(
            "# key '{quit_key}' is mapped by the user config; sat-hx-ide quit binding skipped\n"
        ));
    } else {
        out.push_str(&format!("\nmap {quit_key} quit\n"));
    }

    out.push_str(&format!(
        "\n{}\n",
        helper_map(
            &input.keys.file_manager,
            input,
            &["__file-manager", "open"],
            Some(("file-manager", true)),
        )?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(
            &input.keys.file_manager_dock,
            input,
            &["__file-manager", "toggle-dock"],
            Some(("sat-helper", true)),
        )?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(&input.keys.terminal, input, &["__terminal", "toggle"], None,)?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(
            &input.keys.terminal_zoom,
            input,
            &["__terminal", "zoom"],
            None,
        )?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(&input.keys.mindmap, input, &["__mindmap", "toggle"], None,)?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(
            &input.keys.mindmap_zoom,
            input,
            &["__mindmap", "zoom"],
            None,
        )?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(&input.keys.git, input, &["__git", "open"], None,)?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(&input.keys.review, input, &["__review", "open"], None,)?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(&input.keys.workflow, input, &["__workflow", "open"], None,)?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(&input.keys.venv, input, &["__venv", "toggle"], None,)?
    ));
    out.push_str(&format!(
        "{}\n",
        helper_map(&input.keys.venv_select, input, &["__venv", "select"], None,)?
    ));
    Ok(out)
}

/// One `map <key> launch ... sat-hx-ide <helper>` line.
///
/// `overlay_role` tags windows that become session panes: the file-manager
/// overlay runs Yazi in place and needs the `file-manager` role plus the
/// `SAT_FLOAT_WINDOW` marker (kitty does not report overlay windows in
/// `kitten @ ls`, so sat-hx-ide marks them at launch).
#[allow(clippy::too_many_arguments)]
fn helper_map(
    key: &str,
    input: &KittyRuntimeConfigInput<'_>,
    helper: &[&str],
    overlay_role: Option<(&str, bool)>,
) -> Result<String> {
    let mut line = format!("map {} launch --type=overlay", kitty_key(key)?);
    if let Some((role, float)) = overlay_role {
        line.push_str(&format!(" --env SAT_HX_ROLE={role}"));
        if float {
            line.push_str(" --env SAT_FLOAT_WINDOW=1");
        }
        line.push_str(&format!(" --title sat:{role}"));
    } else {
        line.push_str(" --title sat:helper");
    }
    line.push_str(" --cwd current");
    line.push_str(&format!(
        " {}",
        shell_quote(&input.executable.to_string_lossy())
    ));
    line.push_str(" --config");
    line.push_str(&format!(
        " {}",
        shell_quote(&input.app_config.to_string_lossy())
    ));
    for part in helper {
        line.push_str(&format!(" {}", shell_quote(part)));
    }
    Ok(line)
}

/// Collect the keys of the user's `map` lines, in kitty notation.
fn user_map_keys(source: &str) -> Vec<String> {
    source
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            let rest = line.strip_prefix("map ")?;
            let key = rest.split_whitespace().next()?;
            kitty_key(key).ok()
        })
        .collect()
}

fn shell_quote(text: &str) -> String {
    if text.chars().all(|c| {
        c.is_ascii_alphanumeric() || matches!(c, '/' | '.' | '-' | '_' | '@' | '%' | ':' | '+')
    }) {
        text.to_string()
    } else {
        format!("'{}'", text.replace('\'', "'\\''"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn keys() -> KeybindingConfig {
        KeybindingConfig::default()
    }

    fn input<'a>(
        source: Option<&'a Path>,
        keys: &'a KeybindingConfig,
    ) -> KittyRuntimeConfigInput<'a> {
        KittyRuntimeConfigInput {
            source,
            destination: Path::new("/runtime/kitty.conf"),
            session_name: "demo",
            keys,
            executable: Path::new("/usr/bin/sat-hx-ide"),
            app_config: Path::new("/home/u/.config/sat-helix-ide/config.toml"),
        }
    }

    #[test]
    fn translates_key_notation() {
        assert_eq!(kitty_key("Ctrl y").unwrap(), "ctrl+y");
        assert_eq!(kitty_key("Alt Shift t").unwrap(), "alt+shift+t");
        assert_eq!(kitty_key("Alt v").unwrap(), "alt+v");
        assert_eq!(kitty_key("ctrl+y").unwrap(), "ctrl+y");
        assert_eq!(kitty_key("alt+shift+t").unwrap(), "alt+shift+t");
        assert!(kitty_key("").is_err());
        assert!(kitty_key("Ctrl !!").is_err());
    }

    #[test]
    fn generates_include_env_and_maps() {
        let keys = keys();
        let out = merge_config("", &input(None, &keys)).unwrap();
        assert!(out.contains("env SAT_SESSION_NAME=demo"));
        assert!(out.contains("\nmap ctrl+q quit\n"));
        assert!(out.contains("map ctrl+y launch --type=overlay --env SAT_HX_ROLE=file-manager --env SAT_FLOAT_WINDOW=1 --title sat:file-manager --cwd current /usr/bin/sat-hx-ide --config /home/u/.config/sat-helix-ide/config.toml __file-manager open"));
        assert!(out.contains("map alt+y launch --type=overlay --env SAT_HX_ROLE=sat-helper --env SAT_FLOAT_WINDOW=1 --title sat:sat-helper --cwd current /usr/bin/sat-hx-ide --config /home/u/.config/sat-helix-ide/config.toml __file-manager toggle-dock"));
        assert!(out.contains("map alt+t launch --type=overlay --title sat:helper --cwd current /usr/bin/sat-hx-ide --config /home/u/.config/sat-helix-ide/config.toml __terminal toggle"));
        assert!(out.contains("map alt+shift+v launch --type=overlay --title sat:helper --cwd current /usr/bin/sat-hx-ide --config /home/u/.config/sat-helix-ide/config.toml __venv select"));
        assert!(!out.contains("include"));
    }

    #[test]
    fn includes_user_config_when_present() {
        let keys = keys();
        let source = Path::new("/home/u/.config/kitty/kitty.conf");
        let out = merge_config("", &input(Some(source), &keys)).unwrap();
        assert!(out.contains("include /home/u/.config/kitty/kitty.conf"));
    }

    #[test]
    fn refuses_to_shadow_user_maps() {
        let keys = keys();
        let source = "map ctrl+y load_config_file\n";
        let err = merge_config(source, &input(None, &keys)).unwrap_err();
        assert!(err.to_string().contains("already mapped"));
        assert!(err.to_string().contains("ctrl+y"));
    }

    #[test]
    fn ignores_unrelated_user_maps() {
        let keys = keys();
        let source = "map ctrl+shift+p show_kitty_commands Overview\nfont_size 11\n";
        let out = merge_config(source, &input(None, &keys)).unwrap();
        assert!(out.contains("map ctrl+y"));
    }

    #[test]
    fn user_quit_binding_wins_over_the_parity_key() {
        let keys = keys();
        let source = "map ctrl+q close_window\n";
        let out = merge_config(source, &input(None, &keys)).unwrap();
        assert!(!out.contains("map ctrl+q quit"));
        assert!(out.contains("sat-hx-ide quit binding skipped"));
    }
}
