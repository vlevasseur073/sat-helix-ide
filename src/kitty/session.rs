//! kitty session-file generation (the analog of Zellij's `layout.kdl`).
//!
//! Verified kitty specifics (see the kitty backend spike):
//! - `layout` lines apply to the current tab only, so every tab re-emits
//!   `layout splits`; `--location` only exists in the splits layout.
//! - `new_tab <title>` takes the title unquoted; quoting leaks into it.
//! - `--location=hsplit` docks below, `--location=vsplit` docks beside.
//! - Pane geometry (dock percent, one-line status bar) is adjusted after
//!   startup through the remote-control socket, which works on every kitty
//!   version — unlike `launch --bias`, which older kitty does not accept.

use crate::config::{CommandConfig, DockPosition, MindMapConfig, TerminalConfig};
use std::path::Path;

/// Inputs mirroring [`crate::zellij::layout::session_layout`].
pub struct KittySessionInput<'a> {
    pub session_name: &'a str,
    pub project_dir: &'a Path,
    pub editor: &'a CommandConfig,
    pub editor_path: &'a Path,
    pub ai: Option<(&'a CommandConfig, &'a Path)>,
    pub terminal: Option<&'a TerminalConfig>,
    pub mindmap: Option<(&'a MindMapConfig, &'a CommandConfig, &'a Path)>,
    pub executable: &'a Path,
    pub app_config: &'a Path,
}

/// Split location kitty uses to dock a pane relative to the active one.
pub fn dock_location(position: DockPosition) -> &'static str {
    match position {
        DockPosition::Down => "hsplit",
        DockPosition::Right => "vsplit",
    }
}

pub fn session_file(input: &KittySessionInput<'_>) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "# Generated by sat-hx-ide for session '{}'. Edits are overwritten.\n",
        input.session_name
    ));
    out.push_str("layout splits\n");
    out.push_str(&format!(
        "cd {}\n",
        shell_quote(&input.project_dir.to_string_lossy())
    ));

    // Code tab: editor, docked terminal, status bar. kitty session files
    // split the ACTIVE window, so the order defines the tree: the status
    // bar is launched last to sit at the bottom of the chain. The mind map
    // is NOT launched here — it joins after startup through the
    // remote-control socket with the editor focused, which is the only way
    // to dock it beside the editor instead of beside the active window.
    out.push_str(&format!(
        "launch --env SAT_HX_ROLE=editor --title editor {}\n",
        program_argv(input.editor_path, &input.editor.args)
    ));
    if let Some(terminal) = input.terminal.filter(|terminal| terminal.enabled) {
        out.push_str(&format!(
            "launch --location={} --env SAT_HX_ROLE=terminal --title terminal\n",
            dock_location(terminal.dock_position)
        ));
    }
    out.push_str(&format!(
        "launch --location=hsplit {}\n",
        statusbar_command(input)
    ));

    // AI tab (single window plus the status bar).
    if let Some((ai, ai_path)) = input.ai {
        out.push_str("new_tab ai\n");
        out.push_str("layout splits\n");
        out.push_str(&format!(
            "launch --env SAT_HX_ROLE=ai --title ai {}\n",
            program_argv(ai_path, &ai.args)
        ));
        out.push_str(&format!(
            "launch --location=hsplit {}\n",
            statusbar_command(input)
        ));
    }
    out
}

/// `<program> <args...>` with shell-style quoting for the session file.
fn program_argv(program: &Path, args: &[String]) -> String {
    let mut out = shell_quote(&program.to_string_lossy());
    for arg in args {
        out.push(' ');
        out.push_str(&shell_quote(arg));
    }
    out
}

/// Arguments of the `__status-bar run` helper window.
fn statusbar_command(input: &KittySessionInput<'_>) -> String {
    let mut out = String::from("--env SAT_HX_ROLE=statusbar --title sat-status-bar");
    for arg in [
        input.executable.to_string_lossy().into_owned(),
        "--config".to_string(),
        input.app_config.to_string_lossy().into_owned(),
        "__status-bar".to_string(),
        "run".to_string(),
        "--session".to_string(),
        input.session_name.to_string(),
        "--project-dir".to_string(),
        input.project_dir.to_string_lossy().into_owned(),
    ] {
        out.push(' ');
        out.push_str(&shell_quote(&arg));
    }
    out
}

/// kitty session files tokenize launch arguments like a shell.
fn shell_quote(text: &str) -> String {
    if text.chars().all(|c| {
        c.is_ascii_alphanumeric() || matches!(c, '/' | '.' | '-' | '_' | '@' | '%' | ':' | '+')
    }) {
        text.to_string()
    } else {
        format!("'{}'", text.replace('\'', "'\\''"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn editor_config() -> CommandConfig {
        CommandConfig::new("hx")
    }

    #[test]
    fn docks_editor_terminal_statusbar_and_ai_tab() {
        let editor = editor_config();
        let ai = CommandConfig::new("agent");
        let input = KittySessionInput {
            session_name: "demo",
            project_dir: Path::new("/proj/my demo"),
            editor: &editor,
            editor_path: Path::new("/usr/bin/hx"),
            ai: Some((&ai, Path::new("/usr/bin/agent"))),
            terminal: Some(&TerminalConfig {
                enabled: true,
                dock_percent: 15,
                dock_position: DockPosition::Down,
            }),
            mindmap: None,
            executable: Path::new("/usr/bin/sat-hx-ide"),
            app_config: Path::new("/home/u/.config/sat-helix-ide/config.toml"),
        };
        let out = session_file(&input);
        assert!(out.contains("layout splits\n"));
        assert!(out.contains("cd '/proj/my demo'\n"));
        assert!(out.contains("--env SAT_HX_ROLE=editor --title editor /usr/bin/hx\n"));
        assert!(
            out.contains("launch --location=hsplit --env SAT_HX_ROLE=terminal --title terminal\n")
        );
        // The status bar is the last window of the code tab.
        let code_tab = &out[..out.find("new_tab").unwrap_or(out.len())];
        assert_eq!(
            code_tab.matches("SAT_HX_ROLE=statusbar").count(),
            1,
            "status bar launches once per tab"
        );
        assert!(out.contains(
            "launch --location=hsplit --env SAT_HX_ROLE=statusbar --title sat-status-bar /usr/bin/sat-hx-ide --config /home/u/.config/sat-helix-ide/config.toml __status-bar run --session demo --project-dir '/proj/my demo'\n"
        ));
        assert!(out.contains("new_tab ai\nlayout splits\n"));
        assert!(out.contains("--env SAT_HX_ROLE=ai --title ai /usr/bin/agent\n"));
        // Every tab gets its own status bar, like Zellij's tab template.
        assert_eq!(out.matches("SAT_HX_ROLE=statusbar").count(), 2);
    }

    #[test]
    fn mindmap_is_not_part_of_the_session_file() {
        let editor = editor_config();
        let mindmap_config = CommandConfig::new("shiki");
        let mindmap = MindMapConfig {
            enabled: true,
            dock_percent: 40,
            dock_position: DockPosition::Right,
        };
        let input = KittySessionInput {
            session_name: "demo",
            project_dir: Path::new("/p"),
            editor: &editor,
            editor_path: Path::new("/usr/bin/hx"),
            ai: None,
            terminal: None,
            mindmap: Some((&mindmap, &mindmap_config, Path::new("/usr/bin/shiki"))),
            executable: Path::new("/usr/bin/sat-hx-ide"),
            app_config: Path::new("/cfg.toml"),
        };
        let out = session_file(&input);
        // The mind map joins post-spawn via remote control.
        assert!(!out.contains("mindmapping"));
        // With no terminal, the status bar is the window after the editor.
        let editor_line = out
            .lines()
            .position(|line| line.contains("SAT_HX_ROLE=editor"))
            .unwrap();
        let statusbar_line = out
            .lines()
            .position(|line| line.contains("SAT_HX_ROLE=statusbar"))
            .unwrap();
        assert_eq!(statusbar_line, editor_line + 1);
    }

    #[test]
    fn terminal_and_mindmap_disabled_or_missing_are_skipped() {
        let editor = editor_config();
        let input = KittySessionInput {
            session_name: "demo",
            project_dir: Path::new("/p"),
            editor: &editor,
            editor_path: Path::new("/usr/bin/hx"),
            ai: None,
            terminal: None,
            mindmap: None,
            executable: Path::new("/usr/bin/sat-hx-ide"),
            app_config: Path::new("/cfg.toml"),
        };
        let out = session_file(&input);
        assert!(!out.contains("SAT_HX_ROLE=terminal"));
        assert!(!out.contains("SAT_HX_ROLE=mindmapping"));
        assert!(!out.contains("new_tab"));
    }

    #[test]
    fn quotes_paths_with_spaces() {
        assert_eq!(shell_quote("/plain/path"), "/plain/path");
        assert_eq!(shell_quote("/has space"), "'/has space'");
        assert_eq!(shell_quote("/it's"), "'/it'\\''s'");
    }

    #[test]
    fn maps_dock_positions() {
        assert_eq!(dock_location(DockPosition::Down), "hsplit");
        assert_eq!(dock_location(DockPosition::Right), "vsplit");
    }
}
